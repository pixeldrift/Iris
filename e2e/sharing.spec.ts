test('a shared group carries a person mark and shows who is in it; sharing it again after taking it back reaches the other person', async ({ browser }) => {
  test.setTimeout(170_000)
  const annEmail = `tann${stamp}@example.com`
  const bobEmail = `tbob${stamp}@example.com`
  const ann = await (await browser.newContext({ viewport: { width: 1200, height: 900 } })).newPage()
  const bob = await (await browser.newContext({ viewport: { width: 1200, height: 900 } })).newPage()
  await signUp(ann, 'Ann Archer', annEmail)
  await signUp(bob, 'Bob Builder', bobEmail)
  await ann.getByRole('button', { name: /Address book/ }).first().click()
  await ann.getByRole('button', { name: 'Add a person' }).last().click()
  await ann.getByPlaceholder('First name').fill('Bobby')
  await ann.getByPlaceholder('Email').fill(bobEmail)
  await ann.getByRole('button', { name: 'Save', exact: true }).click()
  await ann.getByRole('button', { name: 'Send invitation' }).click()
  await bob.reload()
  await bob.locator('[aria-label^="Account"]').click()
  await bob.getByRole('button', { name: /Notifications/ }).click()
  await bob.getByRole('button', { name: 'Review' }).click()
  await bob.getByRole('button', { name: 'Accept', exact: true }).click()
  await ann.reload()

  const share = async () => {
    await row(ann, 'Round two').locator('button[aria-haspopup=dialog]').click()
    await ann.getByRole('button', { name: 'Share', exact: true }).click()
    await ann.getByRole('button', { name: 'Share this group' }).click()
    await ann.getByRole('button', { name: 'Invite', exact: true }).click()
    await ann.getByRole('dialog').getByRole('button', { name: 'Done', exact: true }).click()
  }
  const join = async () => {
    await bob.reload()
    await bob.locator('[aria-label^="Account"]').click()
    await bob.getByRole('button', { name: /Notifications/ }).click()
    await bob.getByRole('button', { name: 'Join' }).click()
    await bob.getByRole('button', { name: 'Close', exact: true }).click()
  }
  await ann.getByText('Groups', { exact: true }).locator('xpath=ancestor::*[self::header or self::div][1]').getByRole('button').last().click()
  await ann.getByLabel('Group name').fill('Round two')
  await ann.getByLabel('Group name').press('Enter')
  await row(ann, 'Round two').click()
  await ann.keyboard.press('n')
  await ann.keyboard.type('First thing')
  await ann.keyboard.press('Enter')
  await share()
  await join()
  await expect(row(bob, 'Round two')).toBeVisible({ timeout: 20_000 })
  await row(bob, 'Round two').click()
  await expect(bob.getByText('First thing').first()).toBeVisible({ timeout: 20_000 })
  // the pond names the shared group with the person mark, and shows who is in it
  await expect(bob.getByRole('img', { name: 'Shared group' }).first()).toBeVisible()
  await expect(ann.getByRole('group', { name: 'People in shared groups' })).toBeVisible({ timeout: 20_000 })
  // tapping a face opens that person's card
  await ann.getByRole('group', { name: 'People in shared groups' }).getByRole('button').first().click()
  await expect(ann.getByRole('heading', { name: /Bob/ })).toBeVisible()
  await ann.keyboard.press('Escape')
  await expect(ann.getByRole('dialog')).toHaveCount(0)

  // Ann takes the group back with no copy; sharing it again reaches Bob again
  await row(ann, 'Round two').locator('button[aria-haspopup=dialog]').click()
  await ann.getByRole('button', { name: 'Sharing' }).click()
  await ann.getByRole('button', { name: 'Stop sharing' }).click()
  await ann.getByRole('button', { name: 'Stop, no copy' }).click()
  await expect(ann.getByRole('button', { name: 'Share this group' })).toBeVisible() // (the dialog now offers to share it afresh)
  await ann.keyboard.press('Escape')
  await expect(ann.getByRole('dialog')).toHaveCount(0)
  await bob.reload()
  await expect(row(bob, 'Round two')).toHaveCount(0, { timeout: 20_000 })
  await expect(row(ann, 'Round two').getByRole('img', { name: 'Shared group' })).toHaveCount(0)
  await share()
  await join()
  await expect(row(bob, 'Round two')).toBeVisible({ timeout: 20_000 })
  await row(bob, 'Round two').click()
  await expect(bob.getByText('First thing').first()).toBeVisible({ timeout: 20_000 })
})

